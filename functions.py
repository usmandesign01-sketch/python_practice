#what is function in python?
# simple definition of function is a block of code which only runs when it is called. we can pass data, known as parameters into a function. a function can return data as a result.



#how many functions are there in python? there are two types of functions in python. 1. built-in functions 2. user-defined functions
#1. built-in functions are the functions which are already defined in python. for example print(), len(), type() , append , sort, etc.

#2. user-defined functions are the functions which are defined by the user. for example def greet(): print("Hello, World!") is a user-defined function.
#another example of user-defined function is def add(a, b): return a + b. this function takes two parameters a and b and returns their sum.
#other examples of user-defined functions are def subtract(a, b): return a - b, def multiply(a, b): return a * b, def divide(a, b): return a / b. these functions take two parameters a and b and return their difference, product and quotient respectively.


